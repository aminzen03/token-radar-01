// Token Radar — model radar-2.
//
// One sealed snapshot of the protocol universe in, one ranked board out.
//
// WHAT THE BOARD RANKS
// A protocol earns a row when it could plausibly launch a token of its own.
// The rule is the watchlist's own definition, applied to the whole universe:
// pre-token (no market cap, no CoinGecko id, no symbol), not a CEX, not a
// versioned pool (a name ending in V2, v2, 2.0 and the like), not a wrapped,
// staked or bridged product (category Bridge, Canonical Bridge, Liquid
// Staking, Liquid Restaking, Restaked BTC, or a name carrying the whole word
// wrapped, staked or staking, or beginning with an exchange's name). A
// wrapped product of a token that already trades is not a launch candidate:
// WBTC is Bitcoin on Ethereum, Binance staked ETH is ETH in Binance's
// staking product, and neither is waiting on a launch of its own.
//
// The watchlist is the floor, never the ceiling: every watchlist slug is
// covered, and the board adds two more groups — pre-token protocols at or
// above the floor that the watchlist leaves out (Sentora Curator is the
// largest, $2.76B of TVL), and pre-token protocols below the floor, the
// early radar.
//
// IMPLIED VALUE — radar-2
// The value a launch would be worth is anchored in the market's own
// numbers, not in a flat multiple: for each category, the median
// market-cap-to-TVL ratio of the live-token protocols in that category,
// taken from this same snapshot. A category with fewer than three live
// peers falls back to the all-live median. The multiple is clamped to
// [0.05, 1.00] so a thin peer set cannot print an absurd value.
//
//   base      = tvl_usd x category_multiple
//   growth    = clamp(change_7d, -60, 120) per cent
//   growthMult= 1 + (growth / 100) x 0.5
//   maturity  = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   breadth   = 1 + 0.02 x min(chains - 1, 10)
//   implied   = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every
// row, and the dashboard states the constants and lets the reader change
// them in the model sandbox.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

